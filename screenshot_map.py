# -*- coding: utf-8 -*-
from qgis.PyQt.QtGui import (
    QIcon, QPixmap, QPainter, QColor, QPen, QBrush, QFont,
    QPolygonF
)
from qgis.PyQt.QtWidgets import QAction, QFileDialog
from qgis.PyQt.QtCore import QDate, Qt, QPointF, QRectF, QSize
from qgis.PyQt.QtSvg import QSvgGenerator
from qgis.core import (
    QgsProject, QgsPrintLayout, QgsLayoutItemMap,
    QgsLayoutPoint, QgsLayoutSize, QgsUnitTypes,
    QgsLayoutItemScaleBar, QgsLayoutItemLabel,
    QgsLayoutItemPicture, QgsLayoutExporter, QgsApplication
)
import os


def _make_camera_icon(size=64):
    """Zeichnet ein Kamera-Symbol zur Laufzeit (kein externes Bild noetig)."""
    pixmap = QPixmap(size, size)
    pixmap.fill(QColor(0, 0, 0, 0))
    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)

    body = QRectF(size * 0.12, size * 0.30, size * 0.76, size * 0.48)
    painter.setBrush(QBrush(QColor(40, 40, 40)))
    painter.setPen(QPen(QColor(20, 20, 20), size * 0.02))
    painter.drawRoundedRect(body, size * 0.08, size * 0.08)

    hump = QRectF(size * 0.36, size * 0.22, size * 0.28, size * 0.12)
    painter.setBrush(QBrush(QColor(40, 40, 40)))
    painter.drawRoundedRect(hump, size * 0.04, size * 0.04)

    lens_cx, lens_cy = size * 0.5, size * 0.54
    lens_r = size * 0.16
    painter.setBrush(QBrush(QColor(70, 130, 180)))
    painter.setPen(QPen(QColor(20, 20, 20), size * 0.02))
    painter.drawEllipse(QPointF(lens_cx, lens_cy), lens_r, lens_r)

    painter.setBrush(QBrush(QColor(30, 60, 90)))
    painter.setPen(Qt.PenStyle.NoPen)
    painter.drawEllipse(QPointF(lens_cx, lens_cy), lens_r * 0.6, lens_r * 0.6)

    painter.setBrush(QBrush(QColor(200, 230, 255, 180)))
    painter.drawEllipse(
        QPointF(lens_cx - lens_r * 0.25, lens_cy - lens_r * 0.25),
        lens_r * 0.18, lens_r * 0.18
    )

    painter.setBrush(QBrush(QColor(255, 220, 100)))
    painter.setPen(Qt.PenStyle.NoPen)
    painter.drawRoundedRect(
        QRectF(size * 0.70, size * 0.34, size * 0.10, size * 0.06),
        size * 0.02, size * 0.02
    )

    painter.end()
    return QIcon(pixmap)


def _make_north_arrow_svg(path, size=128):
    """Zeichnet einen dezenten Kompass-Nordpfeil als SVG-Datei."""
    generator = QSvgGenerator()
    generator.setFileName(path)
    generator.setSize(QSize(size, size))
    generator.setViewBox(QRectF(0, 0, size, size))
    generator.setTitle("North Arrow")
    generator.setDescription("Generated by ScreenShotMap")

    painter = QPainter(generator)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)

    cx = size / 2.0

    ring_r = size * 0.42
    painter.setBrush(Qt.BrushStyle.NoBrush)
    painter.setPen(QPen(QColor(40, 40, 40), size * 0.02))
    painter.drawEllipse(QPointF(cx, cx), ring_r, ring_r)

    top = QPolygonF([
        QPointF(cx, size * 0.10),
        QPointF(cx - size * 0.08, cx),
        QPointF(cx + size * 0.08, cx),
    ])
    bottom = QPolygonF([
        QPointF(cx, size * 0.90),
        QPointF(cx - size * 0.08, cx),
        QPointF(cx + size * 0.08, cx),
    ])
    painter.setPen(QPen(QColor(40, 40, 40), size * 0.015))
    painter.setBrush(QBrush(QColor(40, 40, 40)))
    painter.drawPolygon(top)
    painter.setBrush(QBrush(QColor(220, 220, 220)))
    painter.drawPolygon(bottom)

    font = painter.font()
    font.setBold(True)
    font.setPixelSize(int(size * 0.14))
    painter.setFont(font)
    painter.setPen(QPen(QColor(40, 40, 40)))
    painter.drawText(
        QRectF(cx - size * 0.1, 0, size * 0.2, size * 0.14),
        Qt.AlignmentFlag.AlignCenter, "N"
    )

    painter.end()


class ScreenShotMap:

    def __init__(self, iface):
        self.iface = iface
        self.action = None

    def initGui(self):
        icon = _make_camera_icon(64)
        self.action = QAction(icon, "ScreenShotMap (DIN A4)", self.iface.mainWindow())
        self.action.setToolTip("Aktuelle Kartenansicht als DIN-A4-Screenshot exportieren")
        self.action.triggered.connect(self.run)
        self.iface.addToolBarIcon(self.action)
        self.iface.addPluginToMenu("&ScreenShotMap", self.action)

    def unload(self):
        self.iface.removePluginMenu("&ScreenShotMap", self.action)
        self.iface.removeToolBarIcon(self.action)
        self.action = None

    def _visible_layer_names(self, canvas):
        root = QgsProject.instance().layerTreeRoot()
        names = []
        for layer in canvas.layers():
            node = root.findLayer(layer.id())
            if node is not None and node.isVisible():
                names.append(layer.name())
        return names

    def run(self):
        canvas = self.iface.mapCanvas()
        canvas_size = canvas.size()
        if canvas_size.height() == 0:
            self.iface.messageBar().pushWarning("ScreenShotMap", "Canvas hat keine gueltige Groesse.")
            return
        canvas_ratio = canvas_size.width() / canvas_size.height()

        PAGE_W, PAGE_H = 297, 210
        MARGIN = 10
        FOOTER_H = 30
        usable_w = PAGE_W - 2 * MARGIN
        usable_h = PAGE_H - MARGIN - FOOTER_H - MARGIN

        if usable_w / usable_h > canvas_ratio:
            map_h = usable_h
            map_w = map_h * canvas_ratio
        else:
            map_w = usable_w
            map_h = map_w / canvas_ratio

        layout = QgsPrintLayout(QgsProject.instance())
        layout.initializeDefaults()
        layout.pageCollection().page(0).setPageSize(
            QgsLayoutSize(PAGE_W, PAGE_H, QgsUnitTypes.LayoutMillimeters)
        )

        map_item = QgsLayoutItemMap(layout)
        layout.addLayoutItem(map_item)
        map_item.attemptResize(QgsLayoutSize(map_w, map_h, QgsUnitTypes.LayoutMillimeters))
        map_x = (PAGE_W - map_w) / 2
        map_item.attemptMove(QgsLayoutPoint(map_x, MARGIN, QgsUnitTypes.LayoutMillimeters))
        map_item.setExtent(canvas.extent())

        # --- Nordpfeil: zur Laufzeit als SVG erzeugt ---
        north_svg = os.path.join(os.path.dirname(__file__), "north_arrow.svg")
        if not os.path.exists(north_svg):
            _make_north_arrow_svg(north_svg)

        north_arrow = QgsLayoutItemPicture(layout)
        north_arrow.setBackgroundEnabled(False)
        north_arrow.setFrameEnabled(False)
        north_arrow.setPicturePath(north_svg)
        layout.addLayoutItem(north_arrow)
        north_arrow.attemptResize(QgsLayoutSize(12, 12, QgsUnitTypes.LayoutMillimeters))
        north_arrow.attemptMove(
            QgsLayoutPoint(map_x + map_w - 16, MARGIN + 4, QgsUnitTypes.LayoutMillimeters)
        )

        # --- Massstabsbalken ---
        footer_y = MARGIN + map_h + 3
        scalebar = QgsLayoutItemScaleBar(layout)
        scalebar.setLinkedMap(map_item)
        scalebar.setStyle("Line Ticks Up")
        scalebar.setUnits(QgsUnitTypes.DistanceMeters)
        scalebar.setUnitLabel("m")
        scalebar.setNumberOfSegments(2)
        scalebar.setNumberOfSegmentsLeft(0)
        scalebar.setUnitsPerSegment(500)
        scalebar.applyDefaultSize()
        layout.addLayoutItem(scalebar)

        bar_width = scalebar.sizeWithUnits().width()
        scalebar.attemptMove(
            QgsLayoutPoint(
                map_x + map_w - bar_width,
                footer_y,
                QgsUnitTypes.LayoutMillimeters
            )
        )

        # --- Datenquellen ---
        visible_layers = self._visible_layer_names(canvas)
        if visible_layers:
            source_lines = ["Datenquelle:"]
            for name in visible_layers:
                source_lines.append("  - " + name)
        else:
            source_lines = ["Datenquelle: -"]
        source_lines.append("Stand: " + QDate.currentDate().toString("yyyy-MM-dd"))
        label_text = "\n".join(source_lines)

        label = QgsLayoutItemLabel(layout)
        label.setText(label_text)
        label.setFont(QFont("Arial", 8))
        label.adjustSizeToText()
        layout.addLayoutItem(label)
        label.attemptMove(
            QgsLayoutPoint(map_x, footer_y, QgsUnitTypes.LayoutMillimeters)
        )

        # --- Export ---
        file_path, _ = QFileDialog.getSaveFileName(
            self.iface.mainWindow(),
            "Screenshot speichern",
            os.path.expanduser("~/screenshot_a4.png"),
            "PNG-Bild (*.png)"
        )
        if not file_path:
            return

        if not file_path.lower().endswith(".png"):
            file_path += ".png"

        exporter = QgsLayoutExporter(layout)
        settings = QgsLayoutExporter.ImageExportSettings()
        settings.dpi = 300
        result = exporter.exportToImage(file_path, settings)

        if result == QgsLayoutExporter.Success:
            self.iface.messageBar().pushSuccess("ScreenShotMap", f"Gespeichert: {file_path}")
        else:
            self.iface.messageBar().pushWarning("ScreenShotMap", "Export fehlgeschlagen.")